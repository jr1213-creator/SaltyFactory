import { DataTable, EmptyState, ImageGenerationJobCard, MetricCard, PageHeader, ProviderStatusCard, StatusBadge, WorkflowStepHeader } from "@saltyfactory/ui";
import { parseEnv } from "@saltyfactory/config";
import { getStudioLists } from "../data";

export default async function Page() {
  const { jobs } = await getStudioLists();
  const cfg = parseEnv();
  return <>
    <PageHeader title="Generation Queue" description="Provider-gated job monitoring for image generation and downstream asset processing.">
      <a className="sf-button sf-button-primary" href="/studio/briefs">Send Approved Brief</a>
    </PageHeader>
    <div className="sf-grid sf-grid-3"><MetricCard title="Queued jobs" value={String(jobs.filter((j:any)=>j.status==="queued").length)} /><MetricCard title="Running" value={String(jobs.filter((j:any)=>j.status==="running").length)} tone="info" /><MetricCard title="Failed" value={String(jobs.filter((j:any)=>j.status==="failed").length)} tone="danger" /></div>
    <div className="sf-grid sf-grid-2" style={{ marginTop: 18 }}>
      <section className="sf-card">
        <WorkflowStepHeader step="3" title="Image Generation Jobs" status={cfg.providers.aiImage.enabled ? "provider configured" : "setup needed"} description="The worker must persist generated bytes into private storage and create design asset records before a job can complete." />
        {jobs.length ? <DataTable columns={["Job", "Status", "Provider", "Retries", "Output"]} rows={jobs.map((job:any)=>[
          job.id,
          <StatusBadge key="s" status={job.status ?? "queued"} />,
          job.provider ?? "disabled",
          String(job.retry_count ?? job.retryCount ?? 0),
          job.output_asset_id ?? job.outputAssetId ?? "asset pending"
        ])} /> : <EmptyState title="No generation jobs" description="Jobs appear after an approved prompt is queued against a configured image provider." />}
      </section>
      <ProviderStatusCard title="Image generation provider" status={cfg.providers.aiImage.enabled ? "Configured" : "Disabled"} tone={cfg.providers.aiImage.enabled ? "success" : "warning"} description={cfg.providers.aiImage.enabled ? "Allowed image provider is configured. Generated bytes are stored as private design assets." : "Requires AI_IMAGE_ENABLED=true, HF_API_TOKEN, and HF_IMAGE_MODEL. No placeholder images are generated."} />
    </div>
    {jobs.length ? <div className="sf-grid sf-grid-3" style={{ marginTop: 18 }}>
      {jobs.slice(0, 6).map((job: any) => <ImageGenerationJobCard key={job.id} title={job.title ?? job.id} status={job.status ?? "queued"} prompt={job.prompt ?? job.prompt_text ?? "Prompt stored in private job metadata."} />)}
    </div> : null}
  </>;
}
